import PDFDocument from 'pdfkit';
import QRCode from 'qrcode';
import type { BookingDTO } from './bookingService.js';
import { formatINR } from '../lib/money.js';

const BLUE = '#0B3A8C';
const SAFFRON = '#E8771A';
const RED = '#B42318';

/** Render a DEMO receipt PDF. Every page carries the not-valid-for-travel warning. */
export function renderReceiptPdf(b: BookingDTO, user: { name: string; email: string }): PDFKit.PDFDocument {
  const doc = new PDFDocument({ size: 'A4', margin: 48, info: { Title: `RailwayOne Pro DEMO receipt ${b.bookingRef}`, Author: 'RailwayOne Pro (demo prototype)' } });
  const W = doc.page.width;

  // Diagonal watermark
  doc.save().rotate(-30, { origin: [W / 2, 420] }).fontSize(64).fillColor(RED).opacity(0.08).text('DEMO ONLY', 60, 380, { width: W - 120, align: 'center' }).restore();
  doc.opacity(1);

  // Header band
  doc.rect(0, 0, W, 86).fill(BLUE);
  doc.rect(0, 86, W, 4).fill(SAFFRON);
  doc.fillColor('#fff').fontSize(22).font('Helvetica-Bold').text('RailwayOne Pro', 48, 26);
  doc.fontSize(10).font('Helvetica').text('Demo booking receipt - prototype application', 48, 54);
  doc.fontSize(9).text('Not an Indian Railways product', W - 248, 54, { width: 200, align: 'right' });

  // Warning box
  doc.roundedRect(48, 108, W - 96, 44, 6).fillAndStroke('#FEF3F2', RED);
  doc.fillColor(RED).font('Helvetica-Bold').fontSize(14).text('DEMO ONLY - NOT VALID FOR TRAVEL', 48, 117, { width: W - 96, align: 'center' });
  doc.font('Helvetica').fontSize(8.5).text('This receipt was generated by a software prototype with simulated payments and mock data.', 48, 136, { width: W - 96, align: 'center' });

  const rows: [string, string][] = [
    ['Demo booking ID', b.bookingRef],
    ['Ticket type', b.type === 'PLATFORM' ? 'Platform ticket (demo)' : 'Unreserved journey ticket (demo)'],
    ['Status', b.status.replace('_', ' ')],
    [b.type === 'PLATFORM' ? 'Station' : 'From', `${b.source.name} (${b.source.code})`],
    ...(b.destination ? ([['To', `${b.destination.name} (${b.destination.code})`]] as [string, string][]) : []),
    ['Journey date', b.journeyDate],
    ...(b.trainType ? ([['Train type', `${b.trainType}${b.trainNumber ? ` - ${b.trainNumber} ${b.trainName ?? ''}` : ''}`]] as [string, string][]) : []),
    ['Class', b.classCode === 'PF' ? 'Platform' : 'Second (II)'],
    ['Passengers', b.type === 'PLATFORM' ? `${b.adults} person(s)` : `${b.adults} adult(s), ${b.children} child(ren)`],
    ...(b.distanceKm ? ([['Demo distance', `${b.distanceKm} km (approx.)`]] as [string, string][]) : []),
    ['Booked at', new Date(b.createdAt).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' }) + ' IST'],
    ...(b.paidAt ? ([['Paid at (simulated)', new Date(b.paidAt).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' }) + ' IST']] as [string, string][]) : []),
    ...(b.paymentMethod ? ([['Payment method', b.paymentMethod.replace('_', ' ') + ' (sandbox)']] as [string, string][]) : []),
    ['Booked by', `${user.name} <${user.email}>`],
  ];

  let y = 176;
  doc.fillColor('#101828');
  for (const [k, v] of rows) {
    doc.font('Helvetica').fontSize(9.5).fillColor('#667085').text(k, 48, y, { width: 150 });
    doc.font('Helvetica-Bold').fontSize(10.5).fillColor('#101828').text(v, 200, y, { width: 200 });
    y += 22;
  }

  // QR (simulated)
  if (b.qrPayload) {
    const qr = QRCode.create(b.qrPayload, { errorCorrectionLevel: 'M' });
    const size = qr.modules.size;
    const box = 140;
    const cell = box / size;
    const x0 = W - 48 - box;
    const y0 = 180;
    doc.rect(x0 - 8, y0 - 8, box + 16, box + 16).fill('#fff').stroke();
    doc.fillColor('#101828');
    for (let r = 0; r < size; r++) for (let c = 0; c < size; c++) if (qr.modules.get(r, c)) doc.rect(x0 + c * cell, y0 + r * cell, cell, cell).fill();
    doc.fillColor(RED).font('Helvetica-Bold').fontSize(8).text('SIMULATED QR - NOT A TRAVEL CREDENTIAL', x0 - 20, y0 + box + 14, { width: box + 40, align: 'center' });
  }

  // Fare table
  y += 16;
  doc.moveTo(48, y).lineTo(W - 48, y).strokeColor('#EAECF0').stroke();
  y += 12;
  doc.font('Helvetica-Bold').fontSize(12).fillColor(BLUE).text('Demo fare breakdown', 48, y);
  y += 22;
  const fare = b.fare as { lines?: { label: string; quantity: number; unitPaise: number; amountPaise: number }[]; disclaimer?: string };
  for (const l of fare.lines ?? []) {
    doc.font('Helvetica').fontSize(10).fillColor('#344054').text(`${l.label} x ${l.quantity} @ ${formatINR(l.unitPaise)}`, 48, y);
    doc.text(formatINR(l.amountPaise), W - 248, y, { width: 200, align: 'right' });
    y += 18;
  }
  doc.moveTo(48, y + 2).lineTo(W - 48, y + 2).strokeColor('#EAECF0').stroke();
  y += 10;
  doc.font('Helvetica-Bold').fontSize(12).fillColor('#101828').text('Total (demo)', 48, y);
  doc.text(formatINR(b.totalPaise), W - 248, y, { width: 200, align: 'right' });
  y += 20;
  if (b.refundPaise != null) {
    doc.font('Helvetica').fontSize(10).fillColor('#027A48').text('Demo refund to wallet', 48, y);
    doc.text(formatINR(b.refundPaise), W - 248, y, { width: 200, align: 'right' });
    y += 18;
  }
  doc.font('Helvetica').fontSize(8.5).fillColor('#667085').text(`Fare dataset ${b.fareTableVersion}: ${fare.disclaimer ?? 'Illustrative demo fares only.'}`, 48, y + 8, { width: W - 96 });

  doc.font('Helvetica').fontSize(8).fillColor('#98A2B3').text(
    'RailwayOne Pro is an independent software demonstration. It is not affiliated with, endorsed by, or connected to Indian Railways, CRIS, IRCTC or RailOne. No real ticket has been issued and no real payment was taken.',
    48, doc.page.height - 90, { width: W - 96, align: 'center' },
  );
  doc.end();
  return doc;
}
